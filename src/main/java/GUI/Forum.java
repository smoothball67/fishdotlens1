    private void tampilDataPostingan() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID Postingan"); 
        model.addColumn("Judul");
        model.addColumn("Pengguna");
        model.addColumn("Tanggal");
        
        jTable1.setModel(model); 
        
        service.ForumService forumService = new service.ForumService();
        java.sql.ResultSet rs = forumService.getAllPostingan();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("judul"),
                    rs.getString("nama"),
                    rs.getString("tanggal")
                });
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error tampil tabel forum: " + e.getMessage());
        }
    }

