    private void jButtonYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonYActionPerformed

        int barisTerpilih = jTable1.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            String idPostingan = jTable1.getValueAt(barisTerpilih, 0).toString(); 
            
            service.FavoritService favService = new service.FavoritService();
            String hasil = favService.hapusPostingan(idPostingan);
            
            if (hasil.equals("SUKSES")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Postingan berhasil dihapus dari daftar simpanan!");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal! Postingan ini belum kamu simpan sebelumnya.", "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih postingan di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButtonYActionPerformed

    private void jButtonXActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonXActionPerformed

        int barisTerpilih = jTable1.getSelectedRow(); 

        if (barisTerpilih != -1) { 

            String idPostingan = jTable1.getValueAt(barisTerpilih, 0).toString(); 
            
            service.FavoritService favService = new service.FavoritService();
            String hasil = favService.simpanPostingan(idPostingan);
            
            if (hasil.equals("SUKSES")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Postingan berhasil disimpan!");
            } else if (hasil.equals("SUDAH_ADA")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Kamu sudah menyimpan postingan ini sebelumnya!", "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan postingan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih postingan di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButtonXActionPerformed

