    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
                        
        int baris = jTable1.getSelectedRow();
        
        if (baris != -1) {

            String idPostingan = jTable1.getValueAt(baris, 0).toString();

            txtJudul.setText("");
            txtIsi.setText("");

            service.ForumService forumService = new service.ForumService();
            boolean sudahDisimpan = forumService.cekApakahPostinganDisimpan(idPostingan);
 
            if (sudahDisimpan) {
                jButtonX.setText("⭐ Tersimpan");
                jButtonX.setEnabled(false); 
                jButtonY.setEnabled(true); 
            } else {
                jButtonX.setText("Simpan");
                jButtonX.setEnabled(true);
                jButtonY.setEnabled(false);
            }
        }
    
    }//GEN-LAST:event_jTable1MouseClicked

