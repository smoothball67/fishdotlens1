    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String judul = txtJudul.getText();
        String isi = txtIsi.getText(); 
        
        if (judul.isEmpty() || isi.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Judul dan Isi postingan tidak boleh kosong!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        } else {

            service.ForumService forumService = new service.ForumService();
            boolean sukses = forumService.buatPostingan(judul, isi);
            
            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(this, "Berhasil! Postinganmu sudah Terkirim.");
                
                txtJudul.setText("");
                txtIsi.setText("");
                
                tampilDataPostingan(); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengirim postingan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

