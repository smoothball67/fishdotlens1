    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        int barisTerpilih = tblPosting.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
                "Yakin ingin menghapus postingan ini secara permanen?", 
                "Peringatan Hapus", 
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);
                
            if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
                String idPostingan = tblPosting.getValueAt(barisTerpilih, 0).toString(); 
                
                service.ForumService forumService = new service.ForumService();
                boolean sukses = forumService.hapusPostinganPermanen(idPostingan);
                
                if (sukses) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Postingan berhasil dihapus permanen!");
                    
                    
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus postingan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih postingan di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

