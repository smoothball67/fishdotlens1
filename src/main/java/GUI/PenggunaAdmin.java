    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        int barisTerpilih = jTable1.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            String idUser = jTable1.getValueAt(barisTerpilih, 0).toString();
            String namaUser = jTable1.getValueAt(barisTerpilih, 1).toString();
            String roleUser = jTable1.getValueAt(barisTerpilih, 3).toString();
            
            if (!roleUser.equalsIgnoreCase("Penghobi")) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Maaf, tombol ini hanya untuk mengatur tingkat keanggotaan Penghobi!", 
                    "Peringatan", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return; 
            }

            String[] pilihanTingkat = {"Pemula", "Senior"};
            
            String tingkatBaru = (String) javax.swing.JOptionPane.showInputDialog(
                    this,
                    "Pilih tingkat baru untuk " + namaUser + ":",
                    "Ubah Tingkat",
                    javax.swing.JOptionPane.QUESTION_MESSAGE,
                    null,
                    pilihanTingkat,
                    pilihanTingkat[0]
            );
            
            if (tingkatBaru != null) {
                service.PenggunaService pengService = new service.PenggunaService();
                
                if (pengService.ubahTingkat(idUser, tingkatBaru)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Tingkat berhasil diubah menjadi " + tingkatBaru + "!");
                    
                    tampilDataPengguna(txtCari.getText()); 
                    
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah tingkat keanggotaan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih akun Penghobi di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

