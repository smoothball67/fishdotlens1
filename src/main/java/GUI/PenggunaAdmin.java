    private void tampilDataPengguna(String keyword) {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama");
        model.addColumn("Email");
        model.addColumn("Role");
        model.addColumn("Keahlian");
        model.addColumn("Tingkat");
        model.addColumn("Tanggal Daftar");
        
        jTable1.setModel(model); 
        
        service.PenggunaService pengService = new service.PenggunaService();
        java.sql.ResultSet rs = keyword.isEmpty() ? pengService.getAllPengguna() : pengService.cariPengguna(keyword);
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nama"),
                    rs.getString("email"),
                    rs.getString("role"),
                    rs.getString("keahlian") != null ? rs.getString("keahlian") : "-",
                    rs.getString("tingkat_keanggotaan") != null ? rs.getString("tingkat_keanggotaan") : "-",
                    rs.getString("tanggal_daftar")
                });
            }
        } catch (Exception e) {
            System.out.println("Error tampil pengguna: " + e.getMessage());
        }
    }

