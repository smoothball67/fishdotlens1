    private void tampilDataIkan() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID Ikan");       
        model.addColumn("Nama Ikan");  
        model.addColumn("Habitat");
        model.addColumn("Pakan");
        model.addColumn("Penyakit");
        
        tblIkan.setModel(model); 
        
        service.EnsiklopediaService ensiService = new service.EnsiklopediaService();
        java.sql.ResultSet rs = ensiService.getAllIkan();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nama_spesies"),
                    rs.getString("habitat"),
                    rs.getString("pakan"),
                    rs.getString("penyakit")
                });
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error tampil tabel ensiklopedia: " + e.getMessage());
        }
    }

