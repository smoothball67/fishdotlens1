    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String keyword = txtCari.getText(); 

        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID Ikan");
        model.addColumn("Nama Ikan");
        model.addColumn("Habitat");
        model.addColumn("Pakan");
        model.addColumn("Penyakit");
        
        tblIkan.setModel(model); 
        
        service.EnsiklopediaService ensiService = new service.EnsiklopediaService();
        
        java.sql.ResultSet rs;
        if (keyword.isEmpty()) {
            rs = ensiService.getAllIkan();
        } else {
            rs = ensiService.cariIkan(keyword);
        }
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nama_spesies"),
                    rs.getString("habitat"),
                    rs.getString("pakan"),
                    rs.getString("penyakit")
                });
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error cari tabel ensiklopedia: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        int barisTerpilih = tblIkan.getSelectedRow(); 

        if (barisTerpilih != -1) { 

            String idIkan = tblIkan.getValueAt(barisTerpilih, 0).toString();
            
            service.FavoritService favService = new service.FavoritService();

            String hasil = favService.simpanIkan(idIkan);
            
            if (hasil.equals("SUKSES")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Berhasil ditambahkan ke Ikan Favorit!");
            } else if (hasil.equals("SUDAH_ADA")) {

                javax.swing.JOptionPane.showMessageDialog(this, "Kamu telah menambahkan ini di favorit!", "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan ke database!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih ikan di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

