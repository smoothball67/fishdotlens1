    private void jButton10ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton10ActionPerformed

        int barisTerpilih = tblIkan.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
                "Yakin ingin menghapus ikan ini dari ensiklopedia?", 
                "Konfirmasi Hapus", 
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);
                
            if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
                String idIkan = tblIkan.getValueAt(barisTerpilih, 0).toString(); 
                
                service.EnsiklopediaService enService = new service.EnsiklopediaService();
                if (enService.hapusIkanPermanen(idIkan)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ikan berhasil dihapus!");
                    tampilDataIkan();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus ikan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih data ikan di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton10ActionPerformed

