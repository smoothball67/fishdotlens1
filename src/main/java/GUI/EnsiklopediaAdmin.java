    private void jButton15ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton15ActionPerformed
        String nama = txtnama.getText();
        String habitat = txthabitat.getText();
        String pakan = txtpakan.getText();
        String penyakit = txtpenyakit.getText();
        
        if (nama.isEmpty() || habitat.isEmpty() || pakan.isEmpty() || penyakit.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Semua kolom harus diisi!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        service.EnsiklopediaService enService = new service.EnsiklopediaService();
        if (enService.tambahIkan(nama, habitat, pakan, penyakit)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data Ikan berhasil ditambahkan!");
            tampilDataIkan(); 
            
            txtnama.setText("");
            txthabitat.setText("");
            txtpakan.setText("");
            txtpenyakit.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menambahkan data ikan!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton15ActionPerformed

