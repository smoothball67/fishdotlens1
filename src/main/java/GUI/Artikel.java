    private void tampilDataArtikel() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID"); 
        model.addColumn("Judul");   
        model.addColumn("Penulis");  
        model.addColumn("Status");  
        model.addColumn("Isi");      
        

        jTable1.setModel(model); 
        
        service.ArtikelService artService = new service.ArtikelService();
        java.sql.ResultSet rs = artService.getAllArtikel();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("judul"),
                    rs.getString("penulis"),
                    rs.getString("status"),
                    rs.getString("isi")
                });
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error tampil artikel: " + e.getMessage());
        }
    }

