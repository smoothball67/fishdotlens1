    private void txtCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCariActionPerformed

        String keyword = txtCariArtikel.getText();

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        service.ArtikelService artService = new service.ArtikelService();
        java.sql.ResultSet rs;

        if (keyword.isEmpty()) {
            rs = artService.getAllArtikel();
        } else {
            rs = artService.cariArtikel(keyword);
        }

        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"), rs.getString("judul"), rs.getString("penulis"), rs.getString("status"), rs.getString("isi")
                });
            }
        } catch (Exception e) {
            System.out.println("Error cari: " + e.getMessage());
        }
    }//GEN-LAST:event_txtCariActionPerformed

