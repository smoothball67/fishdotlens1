    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked

        int baris = jTable1.getSelectedRow();
        
        if (baris != -1) { 
            String idArtikel = jTable1.getValueAt(baris, 0).toString(); 
            String judul = jTable1.getValueAt(baris, 1).toString(); 
            
            lblDetailPenulis.setText(": " + jTable1.getValueAt(baris, 2).toString());
            lblDetailStatus.setText(": " + jTable1.getValueAt(baris, 3).toString());
            txtDetailIsi.setText(jTable1.getValueAt(baris, 4).toString());
            
            service.FavoritService favService = new service.FavoritService();
            boolean sudahDisimpan = favService.cekApakahSudahDisimpan(idArtikel);
            
            if (sudahDisimpan) {
                lblDetailJudul.setText(": ⭐ " + judul); 
                
                jButton2.setText("⭐ Tersimpan");
                jButton2.setEnabled(false);
                jButton1.setEnabled(true); 
            } else {
                lblDetailJudul.setText(": " + judul); 
                
                jButton2.setText("Simpan");
                jButton2.setEnabled(true);  
                jButton1.setEnabled(false);  
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       int barisTerpilih = jTable1.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            String idArtikel = jTable1.getValueAt(barisTerpilih, 0).toString(); // Ambil ID
            
            service.FavoritService favService = new service.FavoritService();
            String hasil = favService.simpanArtikel(idArtikel);
            
            if (hasil.equals("SUKSES")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Artikel berhasil disimpan!");
            } else if (hasil.equals("SUDAH_ADA")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Kamu sudah menyimpan artikel ini sebelumnya!", "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan artikel!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih artikel di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

