    private void tampilDataArtikelPending() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID");  
        model.addColumn("Judul"); 
        model.addColumn("Penulis");
        model.addColumn("Isi");
        
        jTable2.setModel(model); 
        
        jTable2.getColumnModel().getColumn(3).setMinWidth(0);
        jTable2.getColumnModel().getColumn(3).setMaxWidth(0);
        jTable2.getColumnModel().getColumn(3).setWidth(0);
        
        service.ArtikelService artService = new service.ArtikelService();
        java.sql.ResultSet rs = artService.getArtikelPending();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("judul"),
                    rs.getString("penulis"),
                    rs.getString("isi")
                });
            }
        } catch (Exception e) {
            System.out.println("Error tampil artikel pending: " + e.getMessage());
        }
    }

