    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed

        int barisTerpilih = jTable2.getSelectedRow(); 

        if (barisTerpilih != -1) { 
            String idArtikel = jTable2.getValueAt(barisTerpilih, 0).toString(); 
            
            service.ArtikelService artService = new service.ArtikelService();
            boolean sukses = artService.approveArtikel(idArtikel);
            
            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(this, "Artikel berhasil disetujui dan akan tayang untuk Penghobi!");
                
                tampilDataArtikelPending(); 
                
                txtIsiArtikel.setText(""); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyetujui artikel!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih artikel di tabel terlebih dahulu!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton8ActionPerformed

