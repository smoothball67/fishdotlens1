    private void lblNamaDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_lblNamaDetailActionPerformed

        String namaBaru = javax.swing.JOptionPane.showInputDialog(this,
            "Masukkan nama baru kamu:",
            "Ubah Nama",
            javax.swing.JOptionPane.PLAIN_MESSAGE);

        if (namaBaru != null && !namaBaru.trim().isEmpty()) {

            service.ProfilService profilService = new service.ProfilService();
            boolean sukses = profilService.updateNama(namaBaru);

            if (sukses) {

                javax.swing.JOptionPane.showMessageDialog(this, "Nama berhasil diperbarui!");

                lblNamaDetail.setText(namaBaru);

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah nama!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_lblNamaDetailActionPerformed

