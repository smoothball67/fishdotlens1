    private void tampilDataProfil() {
        service.ProfilService profilService = new service.ProfilService();
        java.sql.ResultSet rs = profilService.getProfilUser();
        
        try {
            if (rs != null && rs.next()) {
                lblNama.setText(": " + rs.getString("nama"));
                lblEmail.setText(": " + rs.getString("email"));
                lblRole.setText(": " + rs.getString("role"));
                
                String tingkat = rs.getString("tingkat_keanggotaan");
                lblTingkat.setText(": " + (tingkat != null ? tingkat : "Pemula")); 
                
                String tanggal = rs.getString("tanggal_daftar");
                lblTanggal.setText(": " + (tanggal != null ? tanggal : "-"));
            }
        } catch (Exception e) {
            System.out.println("Error tampil profil: " + e.getMessage());
        }
    }
