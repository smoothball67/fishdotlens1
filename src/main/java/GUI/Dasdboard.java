    private void tampilIkanPopuler() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Nama Ikan");
        model.addColumn("Habitat");
        
        jTable1.setModel(model); 
        
        service.EnsiklopediaService ensiService = new service.EnsiklopediaService();
        ResultSet rs = ensiService.getIkanPopuler();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("nama_spesies"),
                    rs.getString("habitat")
                });
            }
        } catch (SQLException e) {
            System.out.println("Error tampil tabel: " + e.getMessage());
        }
    }
    
    private void tampilPostinganTerbaru() {
        // 1. Buat "kanvas" tabel dengan nama kolom sesuai desainmu
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("Judul");
        model.addColumn("Pengguna");
        
        // 2. Pasang ke tabel (Cek desainmu, biasanya ini jTable2)
        // PENTING: Ganti jTable2 dengan nama variabel tabel postingan di GUI-mu
        jTable2.setModel(model); 
        
        // 3. Panggil ForumService
        service.ForumService forumService = new service.ForumService();
        java.sql.ResultSet rs = forumService.getPostinganTerbaru();
        
        // 4. Masukkan data
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("judul"),
                    rs.getString("nama")
                });
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error tampil postingan: " + e.getMessage());
        }
    }
    
    private void tampilRingkasanData() {
        service.DashboardService dashService = new service.DashboardService();
        
        String jumlahIkan = dashService.getTotalIkan();
        String jumlahArtikel = dashService.getTotalArtikelFavorit();
        String jumlahPost = dashService.getTotalPostinganFavorit();
        
        lblTotalIkan.setText(jumlahIkan);
        lblTotalArtikel.setText(jumlahArtikel);
        lblTotalPostingan.setText(jumlahPost);
    }

