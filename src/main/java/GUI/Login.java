    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String email = txtEmail.getText().trim();
        String password = txtPassword.getText().trim(); 
        
        if (email.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Email dan Password wajib diisi!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        

        service.LoginService loginService = new service.LoginService();
        String roleUser = loginService.prosesLogin(email, password); 
        

        if (roleUser != null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selamat Datang! Login berhasil sebagai " + roleUser);
            
            if (roleUser.equalsIgnoreCase("Admin")) {
                GUI.DashboardAdmin adminDash = new GUI.DashboardAdmin();
                adminDash.setVisible(true);
                
            } else if (roleUser.equalsIgnoreCase("Penghobi")) {

                GUI.Dasdboard penghobiDash = new GUI.Dasdboard(); 
                penghobiDash.setVisible(true);
                
            } else if (roleUser.equalsIgnoreCase("Mentor")) {

                GUI.DashboardMentor mentorDash = new GUI.DashboardMentor();
                mentorDash.setVisible(true);
            }
            
            this.dispose(); 
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Email atau Password salah! Silakan coba lagi.", "Login Gagal", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

