    private void tampilAktivitasPendaftaran() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("Nama");
        model.addColumn("Email");
        model.addColumn("Role");
        model.addColumn("Tingkat Keanggotaan");
        model.addColumn("Tanggal Daftar");
        
        jTable1.setModel(model); 
        
        service.DashboardService dashService = new service.DashboardService();
        java.sql.ResultSet rs = dashService.getPendaftarTerbaru();
        
        try {
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("nama"),
                    rs.getString("email"),
                    rs.getString("role"),
                    rs.getString("tingkat_keanggotaan") != null ? rs.getString("tingkat_keanggotaan") : "-",
                    rs.getString("tanggal_daftar")
                });
            }
        } catch (Exception e) {
            System.out.println("Error tampil pendaftar terbaru: " + e.getMessage());
        }
    }

